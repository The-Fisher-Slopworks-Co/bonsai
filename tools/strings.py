def unit(value):
    return {"stringUnit": {"state": "translated", "value": value}}


def build():
    strings = {}
    for key, (en, ru) in S.items():
        strings[key] = {
            "extractionState": "manual",
            "localizations": {"en": unit(en), "ru": unit(ru)},
        }
    for key, langs in P.items():
        locs = {}
        for lang, forms in langs.items():
            locs[lang] = {"variations": {"plural": {cat: unit(text) for cat, text in forms.items()}}}
        strings[key] = {"extractionState": "manual", "localizations": locs}
    return {"sourceLanguage": "en", "strings": dict(sorted(strings.items())), "version": "1.0"}


